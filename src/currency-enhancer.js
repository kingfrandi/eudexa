const allCurrencies = CURRENCY_LIST.split('\n').map(row => {
  const [code, es, en] = row.split('|');
  return { code, es, en };
});

// Demo rates already available in EUDEXA. Other currencies are selectable now,
// but will show “rate unavailable” until the real-time FX API is connected.
const demoRates = { USD: 1, EUR: 0.92, DOP: 59.1, GBP: 0.78, JPY: 156.4, MXN: 16.9 };

function enhanceCurrencyConverter() {
  const from = document.getElementById('from');
  const to = document.getElementById('to');
  const amount = document.getElementById('amount');
  const result = document.getElementById('result');
  const pair = document.getElementById('pair');
  if (!from || !to || !amount || !result || !pair) return;

  const currentFrom = from.value || 'USD';
  const currentTo = to.value || 'DOP';
  const makeOptions = (selected) => allCurrencies.map(c => `<option value="${c.code}" ${c.code===selected?'selected':''}>${c.code} — ${c.es}</option>`).join('');
  from.innerHTML = makeOptions(currentFrom);
  to.innerHTML = makeOptions(currentTo);

  const update = () => {
    const value = Number(amount.value) || 0;
    const f = from.value;
    const t = to.value;
    pair.textContent = `${f} → ${t}`;
    if (demoRates[f] == null || demoRates[t] == null) {
      result.textContent = '—';
      result.title = 'Tasa de demostración no disponible para esta moneda. Conectaremos datos en tiempo real en la siguiente fase.';
      return;
    }
    const converted = value / demoRates[f] * demoRates[t];
    result.textContent = `${new Intl.NumberFormat(undefined,{maximumFractionDigits:2}).format(converted)} ${t}`;
    result.title = '';
  };

  [amount, from, to].forEach(el => {
    if (el.dataset.currencyEnhanced === '1') return;
    el.dataset.currencyEnhanced = '1';
    el.addEventListener('input', update);
    el.addEventListener('change', update);
  });
  update();
}

let lastConverterSignature = '';
const watchConverter = () => {
  const converter = document.getElementById('converter');
  if (!converter) return;
  const signature = [document.getElementById('from'), document.getElementById('to')].map(el => el && el.options.length).join('|');
  if (signature !== lastConverterSignature) {
    lastConverterSignature = signature;
    enhanceCurrencyConverter();
  }
};

const observer = new MutationObserver(watchConverter);
observer.observe(document.body, { childList: true, subtree: true });
watchConverter();
